/**
 * jsPDF's built-in fonts do not support every Unicode character.
 *
 * Normalize the common characters generated by LLMs so the
 * exported PDF remains readable instead of displaying boxes.
 */
function normalizePdfText(value: string): string {
  return value
    .replace(/\r\n/g, "\n")
    .replace(/\r/g, "\n")
    .replace(/[“”]/g, '"')
    .replace(/[‘’]/g, "'")
    .replace(/[–—]/g, "-")
    .replace(/…/g, "...")
    .replace(/•/g, "*")
    .replace(/→/g, "->")
    .replace(/←/g, "<-")
    .replace(/≥/g, ">=")
    .replace(/≤/g, "<=")
    .replace(/≠/g, "!=")
    .replace(/×/g, "x")
    .replace(/÷/g, "/")
    .replace(/\u00A0/g, " ")
    .replace(/[^\x09\x0A\x0D\x20-\x7E]/g, "");
}

/**
 * Remove markdown markers while preserving the readable text.
 */
function stripMarkdown(value: string): string {
  return normalizePdfText(value)
    .replace(/!\[([^\]]*)\]\([^)]+\)/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/`([^`]+)`/g, "$1")
    .replace(/\*\*\*([^*]+)\*\*\*/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/__([^_]+)__/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/_([^_]+)_/g, "$1")
    .trim();
}

function isMarkdownHeading(line: string) {
  return /^#{1,6}\s+/.test(line.trim());
}

function getMarkdownHeadingLevel(line: string): number {
  const match = line.trim().match(/^(#{1,6})\s+/);
  return match ? match[1].length : 0;
}

function isBullet(line: string) {
  return /^\s*[-*+]\s+/.test(line);
}

function isNumberedList(line: string) {
  return /^\s*\d+[.)]\s+/.test(line);
}

function isBlockQuote(line: string) {
  return /^\s*>\s?/.test(line);
}

function isHorizontalRule(line: string) {
  return /^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(line);
}

function cleanBullet(line: string) {
  return stripMarkdown(
    line.replace(/^\s*[-*+]\s+/, ""),
  );
}

function cleanNumberedList(line: string) {
  const match = line.match(
    /^\s*(\d+)[.)]\s+(.*)$/,
  );

  if (!match) {
    return stripMarkdown(line);
  }

  return {
    number: match[1],
    text: stripMarkdown(match[2]),
  };
}

