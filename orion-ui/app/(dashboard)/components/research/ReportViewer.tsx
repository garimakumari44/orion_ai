/*
 * ============================================================
 * DRAW MARKDOWN HEADING
 * ============================================================
 */

function drawMarkdownHeading(
  renderer: PdfRenderer,
  text: string,
  level: number,
  reportTitle: string,
) {
  const {
    pdf,
  } = renderer;

  const clean =
    stripMarkdown(text);

  if (!clean) {
    return;
  }

  const size =
    level === 1
      ? PDF.heading1Size
      : level === 2
        ? PDF.heading2Size
        : PDF.heading3Size;

  const spacingBefore =
    level === 1
      ? 7
      : level === 2
        ? 6
        : 5;

  const spacingAfter =
    level === 1
      ? 6
      : level === 2
        ? 5
        : 4;

  ensurePdfSpace(
    renderer,
    size * 0.55 +
      spacingBefore +
      spacingAfter +
      8,
    reportTitle,
  );

  renderer.y +=
    spacingBefore;

  pdf.setFont(
    "helvetica",
    "bold",
  );

  pdf.setFontSize(size);

  pdf.setTextColor(
    ...PDF.primaryText,
  );

  const lines =
    pdf.splitTextToSize(
      clean,
      contentWidth(),
    );

  for (const line of lines) {
    ensurePdfSpace(
      renderer,
      size * 0.55,
      reportTitle,
    );

    pdf.text(
      line,
      PDF.marginLeft,
      renderer.y,
    );

    renderer.y +=
      size * 0.55;
  }

  if (level === 1) {
    pdf.setDrawColor(
      ...PDF.accent,
    );

    pdf.setLineWidth(0.5);

    pdf.line(
      PDF.marginLeft,
      renderer.y + 1,
      PDF.marginLeft + 20,
      renderer.y + 1,
    );
  }

  renderer.y +=
    spacingAfter;
}

/*
 * ============================================================
 * DRAW BULLET
 * ============================================================
 */

function drawBullet(
  renderer: PdfRenderer,
  text: string,
  reportTitle: string,
) {
  const {
    pdf,
  } = renderer;

  const safeText =
    cleanBullet(text);

  if (!safeText) {
    return;
  }

  const textWidth =
    contentWidth() -
    PDF.bulletTextIndent;

  pdf.setFont(
    "helvetica",
    "normal",
  );

  pdf.setFontSize(
    PDF.bodyFontSize,
  );

  const lines =
    pdf.splitTextToSize(
      safeText,
      textWidth,
    );

  const totalHeight =
    lines.length *
    PDF.bodyLineHeight;

  ensurePdfSpace(
    renderer,
    totalHeight,
    reportTitle,
  );

  pdf.setFillColor(
    ...PDF.accent,
  );

  pdf.circle(
    PDF.marginLeft +
      2,
    renderer.y - 1.4,
    0.9,
    "F",
  );

  pdf.setTextColor(
    ...PDF.secondaryText,
  );

  lines.forEach(
    (
      line: string,
      index: number,
    ) => {
      if (index > 0) {
        ensurePdfSpace(
          renderer,
          PDF.bodyLineHeight,
          reportTitle,
        );
      }

      pdf.text(
        line,
        PDF.marginLeft +
          PDF.bulletTextIndent,
        renderer.y,
      );

      renderer.y +=
        PDF.bodyLineHeight;
    },
  );

  renderer.y += 1.5;
}

