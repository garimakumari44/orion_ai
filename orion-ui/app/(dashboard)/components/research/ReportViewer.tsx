interface PdfRenderer {
  pdf: jsPDF;
  y: number;
  pageNumber: number;
}

function contentWidth() {
  return (
    PDF.pageWidth -
    PDF.marginLeft -
    PDF.marginRight
  );
}

function availableBottom() {
  return (
    PDF.pageHeight -
    PDF.marginBottom -
    PDF.footerHeight
  );
}

/*
 * ============================================================
 * PAGE HEADER / FOOTER
 * ============================================================
 */

function drawPageHeader(
  renderer: PdfRenderer,
  title: string,
) {
  const { pdf } = renderer;

  pdf.setDrawColor(...PDF.border);
  pdf.setLineWidth(0.25);

  pdf.line(
    PDF.marginLeft,
    15,
    PDF.pageWidth - PDF.marginRight,
    15,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(PDF.tinyFontSize);
  pdf.setTextColor(...PDF.mutedText);

  pdf.text(
    normalizePdfText(title).toUpperCase(),
    PDF.marginLeft,
    10,
  );

  pdf.setTextColor(...PDF.accent);

  pdf.text(
    "RESEARCH REPORT",
    PDF.pageWidth - PDF.marginRight,
    10,
    {
      align: "right",
    },
  );
}

function drawPageFooter(
  renderer: PdfRenderer,
) {
  const { pdf, pageNumber } = renderer;

  const y =
    PDF.pageHeight -
    PDF.marginBottom +
    4;

  pdf.setDrawColor(...PDF.border);
  pdf.setLineWidth(0.25);

  pdf.line(
    PDF.marginLeft,
    y - 5,
    PDF.pageWidth - PDF.marginRight,
    y - 5,
  );

  pdf.setFont("helvetica", "normal");
  pdf.setFontSize(PDF.tinyFontSize);
  pdf.setTextColor(...PDF.mutedText);

  pdf.text(
    "AI RESEARCH ANALYSIS",
    PDF.marginLeft,
    y,
  );

  pdf.text(
    `Page ${pageNumber}`,
    PDF.pageWidth - PDF.marginRight,
    y,
    {
      align: "right",
    },
  );
}

/*
 * ============================================================
 * NEW PAGE
 * ============================================================
 */

function newPdfPage(
  renderer: PdfRenderer,
  title: string,
) {
  renderer.pdf.addPage();

  renderer.pageNumber += 1;

  drawPageHeader(
    renderer,
    title,
  );

  drawPageFooter(renderer);

  renderer.y =
    PDF.marginTop +
    PDF.headerHeight;
}

/*
 * ============================================================
 * ENSURE SPACE
 * ============================================================
 */

function ensurePdfSpace(
  renderer: PdfRenderer,
  requiredHeight: number,
  title: string,
) {
  if (
    renderer.y + requiredHeight <=
    availableBottom()
  ) {
    return;
  }

  newPdfPage(
    renderer,
    title,
  );
}

/*
 * ============================================================
 * DRAW WRAPPED TEXT
 * ============================================================
 */

function drawWrappedText(
  renderer: PdfRenderer,
  text: string,
  options?: {
    fontSize?: number;
    lineHeight?: number;
    fontStyle?: "normal" | "bold" | "italic";
    color?: [number, number, number];
    indent?: number;
    spacingAfter?: number;
    title?: string;
  },
) {
  const {
    pdf,
  } = renderer;

  const fontSize =
    options?.fontSize ??
    PDF.bodyFontSize;

  const lineHeight =
    options?.lineHeight ??
    PDF.bodyLineHeight;

  const fontStyle =
    options?.fontStyle ??
    "normal";

  const color =
    options?.color ??
    PDF.secondaryText;

  const indent =
    options?.indent ??
    0;

  const spacingAfter =
    options?.spacingAfter ??
    0;

  const title =
    options?.title ??
    "Research Report";

  const safeText =
    normalizePdfText(text).trim();

  if (!safeText) {
    return;
  }

  pdf.setFont(
    "helvetica",
    fontStyle,
  );

  pdf.setFontSize(fontSize);
  pdf.setTextColor(...color);

  const maxWidth =
    contentWidth() - indent;

  const lines =
    pdf.splitTextToSize(
      safeText,
      maxWidth,
    );

  for (const line of lines) {
    ensurePdfSpace(
      renderer,
      lineHeight,
      title,
    );

    pdf.text(
      line,
      PDF.marginLeft + indent,
      renderer.y,
    );

    renderer.y += lineHeight;
  }

  renderer.y += spacingAfter;
}

